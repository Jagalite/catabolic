"""Reproduce additive native schema34 and its versioned signature.

No frozen migrations or schema33 signature are rewritten. Default is a check;
--output-dir writes generated artifacts beneath a separate or repository root.
This is reproducibility evidence, not independent review clearance.
"""

import argparse
import hashlib
import json
from contextlib import closing
from pathlib import Path

try:
    from . import native_catalog_schema as foundation
except ImportError:  # Direct script invocation.
    import native_catalog_schema as foundation

REPO = Path(__file__).resolve().parents[1]
RESOURCES = foundation.RESOURCE_PATH
FRAGMENTS = tuple(
    RESOURCES / f"native-catalog/034_{name}.sql"
    for name in ("metadata", "tags", "pins", "logical")
)
SQL = RESOURCES / "migrations/034_native_curation.sql"
SIGNATURE = RESOURCES / "native-schema-34.json"
MANIFEST = Path("tests/parity/native-catalog-curation/schema-manifest.json")


def generate(repo=REPO):
    texts = [path.read_text(encoding="utf-8") for path in (repo / p for p in FRAGMENTS)]
    sql = "-- Generated by scripts/native_catalog_curation_schema.py\n\n" + "\n\n".join(
        texts
    )
    with closing(foundation.legacy_db(repo)) as db:
        db.execute("PRAGMA recursive_triggers=ON")
        db.executescript((repo / foundation.SQL_PATH).read_text(encoding="utf-8"))
        prior = foundation.objects(db)
        old_tables = foundation.tables(db)
        db.executescript(sql)
        current = foundation.objects(db)
        by_name = {(obj[0], obj[1]): obj for obj in current}
        assert all(by_name[obj[0], obj[1]] == obj for obj in prior), (
            "historical DDL changed"
        )
        assert not db.execute("PRAGMA foreign_key_check").fetchall()
        tables = foundation.tables(db)
        manifest = {
            "schema_version": 34,
            "first_native_schema": 33,
            "legacy_target": 32,
            "independent_review": "incomplete; generation does not close blocked review",
            "inputs": {
                str(path): hashlib.sha256((repo / path).read_bytes()).hexdigest()
                for path in (*FRAGMENTS, foundation.SQL_PATH, foundation.SIGNATURE_PATH)
            },
            "new_tables": {
                name: columns
                for name, columns in tables.items()
                if name not in old_tables
            },
            "new_objects": len(current) - len(prior),
            "sql_sha256": hashlib.sha256(sql.encode()).hexdigest(),
        }
    return {
        SQL: sql,
        SIGNATURE: json.dumps(current, indent=2, ensure_ascii=False) + "\n",
        MANIFEST: json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path)
    args = parser.parse_args()
    for path, text in generate().items():
        if args.output_dir:
            destination = args.output_dir / path
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(text, encoding="utf-8")
        elif (REPO / path).read_text(encoding="utf-8") != text:
            raise SystemExit(f"generated artifact differs: {path}")
        print(path)


if __name__ == "__main__":
    main()
