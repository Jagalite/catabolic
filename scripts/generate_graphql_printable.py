"""Freeze Python 3.14.6 str.isprintable for GraphQL inspect error strings.

This is a development generator only. Runtime coercion remains native Rust and
never invokes Python. Rust escape_debug also escapes printable combining marks,
so its Unicode property table cannot substitute for Python's repr behavior.
"""

import argparse
import pathlib
import sys
import unicodedata


def generated_text():
    if sys.version_info[:3] != (3, 14, 6):
        raise SystemExit("run with the pinned Python 3.14.6 reference interpreter")
    ranges = []
    start = None
    for value in range(0x110000):
        if not chr(value).isprintable():
            if start is None:
                start = value
        elif start is not None:
            ranges.append((start, value - 1))
            start = None
    if start is not None:
        ranges.append((start, 0x10FFFF))
    return (
        "// SPDX-FileCopyrightText: 2026 The Catabolic Contributors\n"
        "// SPDX-License-Identifier: MIT\n"
        f"// Generated by scripts/generate_graphql_printable.py; Python 3.14.6, Unicode {unicodedata.unidata_version}.\n"
        "const NONPRINTABLE: &[(u32, u32)] = &[\n"
        + "".join(f"    (0x{a:x}, 0x{b:x}),\n" for a, b in ranges)
        + "];\n"
    )


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="refuse missing or drifted output without writing",
    )
    parser.add_argument(
        "--output",
        type=pathlib.Path,
        default=pathlib.Path(__file__).resolve().parents[1]
        / "crates/catabolic-store/src/graphql_printable.rs",
    )
    args = parser.parse_args(argv)
    expected = generated_text().encode()
    if args.check:
        if not args.output.is_file() or args.output.read_bytes() != expected:
            print(
                f"GraphQL printable table is missing or stale: {args.output}",
                file=sys.stderr,
            )
            return 1
        return 0
    args.output.write_bytes(expected)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
