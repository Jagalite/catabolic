"""Explain the Catabolic 1.0 API disposition for removed names and modules.

This is the only logic in the compatibility layer, and it never touches the
engine. It reads ``_api_disposition.json`` (generated by
``scripts/generate_api_disposition.py``) and turns the standard "no such
module/attribute" failures for deprecated 0.2 names into errors that name
``docs/PYTHON_API_1_0.md``. Names that are not in the disposition keep Python's
standard errors, and supported names are never wrapped or replaced.
"""

import importlib.abc
import json
from pathlib import Path

DOCUMENT = "docs/PYTHON_API_1_0.md"
_state = {}


def _disposition():
    if not _state:
        data = json.loads(
            Path(__file__).with_name("_api_disposition.json").read_text("utf-8")
        )
        _state["removed_modules"] = frozenset(data["removed_modules"])
        _state["deprecated"] = {
            module: frozenset(name.split(".")[0] for name in names)
            for module, names in data["deprecated"].items()
        }
    return _state


def getattr_for(module_name):
    """Build a module ``__getattr__`` for a compatibility module."""

    def __getattr__(name):
        if name in _disposition()["deprecated"].get(module_name, ()):
            raise AttributeError(
                f"module {module_name!r} has no attribute {name!r}: it is "
                f"deprecated and not supported by catabolic 1.0; see {DOCUMENT}"
            )
        raise AttributeError(f"module {module_name!r} has no attribute {name!r}")

    return __getattr__


class _RemovedModules(importlib.abc.MetaPathFinder):
    """Last-resort finder: it only answers for modules listed as removed."""

    def find_spec(self, fullname, path=None, target=None):
        if fullname in _disposition()["removed_modules"]:
            raise ModuleNotFoundError(
                f"No module named {fullname!r}: the module is deprecated and "
                f"removed in catabolic 1.0; see {DOCUMENT}",
                name=fullname,
            )
        return None


def install():
    """Append the removed-module finder once, after every normal finder."""
    import sys

    if not any(isinstance(finder, _RemovedModules) for finder in sys.meta_path):
        sys.meta_path.append(_RemovedModules())
